import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = dirname(dirname(webRoot));

function walk(dir, files = []) {
  if (!existsSync(dir)) return files;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (entry.isFile() && entry.name.endsWith(".md")) files.push(full);
  }
  return files;
}

function idsIn(dir, pattern, exclude = []) {
  const out = [];
  for (const file of walk(dir)) {
    const rel = file.replaceAll("\\", "/");
    if (exclude.some((item) => rel.includes(item))) continue;
    const match = readFileSync(file, "utf8").match(/^id:\s*([KPM]\d{4})\s*$/m);
    if (match && !["K0000", "P0000", "M0000"].includes(match[1]) && pattern.test(match[1])) {
      out.push(match[1]);
    }
  }
  return [...new Set(out)].sort();
}

function researchSlugs() {
  const base = join(repoRoot, "07_项目");
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        entry.name !== "_模板" &&
        existsSync(join(base, entry.name, "research_dossier.md")),
    )
    .map((entry) => entry.name)
    .sort();
}

const knowledge = idsIn(join(repoRoot, "01_知识库"), /^K\d{4}$/, ["/_索引/", "知识库模板.md"]);
const problems = idsIn(join(repoRoot, "02_题目库"), /^P\d{4}$/, ["题目模板.md"]);
const methods = idsIn(join(repoRoot, "12_方法库"), /^M\d{4}$/);
const research = researchSlugs();

const target = join(webRoot, "src", "generated", "known-ids.ts");
const body = `/* GENERATED by scripts/write-known-ids.mjs — not Schema. */
export const KNOWN_KNOWLEDGE = ${JSON.stringify(knowledge)} as const;
export const KNOWN_PROBLEMS = ${JSON.stringify(problems)} as const;
export const KNOWN_METHODS = ${JSON.stringify(methods)} as const;
export const KNOWN_RESEARCH = ${JSON.stringify(research)} as const;

export function isKnownKnowledge(id: string): boolean {
  return (KNOWN_KNOWLEDGE as readonly string[]).includes(id);
}
export function isKnownProblem(id: string): boolean {
  return (KNOWN_PROBLEMS as readonly string[]).includes(id);
}
export function isKnownMethod(id: string): boolean {
  return (KNOWN_METHODS as readonly string[]).includes(id);
}
export function isKnownResearch(slug: string): boolean {
  return (KNOWN_RESEARCH as readonly string[]).includes(slug);
}
`;

writeFileSync(target, body, "utf8");
console.log(
  `wrote ${target} (K${knowledge.length} P${problems.length} M${methods.length} R${research.length})`,
);
